-- H2 本地文件数据库初始化脚本。F1 在此基础上补充业务表。
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

-- ============================================================
-- F1 家政派单：人员台账 / 休假 / 服务单主明细 / 操作记录 / 请求幂等
-- 约定：record_status 只取 NORMAL / VOIDED，一律不物理删除；
--       version 为乐观锁版本；last_request_no 记录最近一次落库请求号。
-- ============================================================

-- 服务人员台账
CREATE TABLE IF NOT EXISTS t_staff (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_no VARCHAR(32) NOT NULL,
    name VARCHAR(64) NOT NULL,
    phone VARCHAR(32),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    record_status VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    version INT NOT NULL DEFAULT 0,
    last_request_no VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_staff_no UNIQUE (staff_no)
);

-- 人员休假
CREATE TABLE IF NOT EXISTS t_staff_leave (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id BIGINT NOT NULL,
    leave_date DATE NOT NULL,
    reason VARCHAR(255),
    record_status VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    version INT NOT NULL DEFAULT 0,
    last_request_no VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_staff_leave_staff_date ON t_staff_leave (staff_id, leave_date);

-- 服务单主表（工单号唯一）
CREATE TABLE IF NOT EXISTS t_service_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no VARCHAR(32) NOT NULL,
    customer_name VARCHAR(64) NOT NULL,
    customer_phone VARCHAR(32),
    address VARCHAR(255),
    service_date DATE NOT NULL,
    time_slot VARCHAR(16) NOT NULL DEFAULT 'AM',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    staff_id BIGINT,
    record_status VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    version INT NOT NULL DEFAULT 0,
    last_request_no VARCHAR(64),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_service_order_no UNIQUE (order_no)
);
CREATE INDEX IF NOT EXISTS idx_service_order_date ON t_service_order (service_date);
CREATE INDEX IF NOT EXISTS idx_service_order_staff_date ON t_service_order (staff_id, service_date);

-- 服务单明细（与主表同生共死；void_cause 区分被替换 REPLACE 与随主冲销 ORDER）
CREATE TABLE IF NOT EXISTS t_service_order_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    item_name VARCHAR(64) NOT NULL,
    quantity INT NOT NULL DEFAULT 1,
    price DECIMAL(10,2) NOT NULL DEFAULT 0,
    record_status VARCHAR(16) NOT NULL DEFAULT 'NORMAL',
    void_cause VARCHAR(16),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_order_item_order ON t_service_order_item (order_id);

-- 操作记录（新增/变更/冲销/恢复/派单/改期均留痕）
CREATE TABLE IF NOT EXISTS t_operation_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    biz_type VARCHAR(32) NOT NULL,
    biz_id BIGINT NOT NULL,
    action VARCHAR(16) NOT NULL,
    request_no VARCHAR(64),
    detail VARCHAR(512),
    trace_id VARCHAR(64),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_operation_log_biz ON t_operation_log (biz_type, biz_id);
-- 老库升级：补 trace_id（新库上一条 CREATE 已含，此句幂等空转）
ALTER TABLE t_operation_log ADD COLUMN IF NOT EXISTS trace_id VARCHAR(64);

-- 请求幂等台账（请求号唯一；重复请求返回首次结果）
CREATE TABLE IF NOT EXISTS t_request_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_no VARCHAR(64) NOT NULL,
    biz_type VARCHAR(32) NOT NULL,
    response_json CLOB,
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_request_record_no UNIQUE (request_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f1-housekeeping', '家政派单：人员台账/服务单主明细/组合检索/幂等/冲销恢复');

-- ============================================================
-- F2 全链路追踪：调用轨迹（每次入口调用一行，可按工单号检索完整调用时序）
-- ============================================================
CREATE TABLE IF NOT EXISTS t_trace_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trace_id VARCHAR(64) NOT NULL,
    order_no VARCHAR(32),
    http_method VARCHAR(8) NOT NULL,
    uri VARCHAR(255) NOT NULL,
    http_status INT NOT NULL,
    success BOOLEAN NOT NULL DEFAULT TRUE,
    cost_ms BIGINT NOT NULL DEFAULT 0,
    error_msg VARCHAR(512),
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_trace_record_order ON t_trace_record (order_no);
CREATE INDEX IF NOT EXISTS idx_trace_record_trace ON t_trace_record (trace_id);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('f2-trace', '全链路TraceId：入口到持久层携带/异步接力/按工单号检索调用时序/敏感字段打码');
